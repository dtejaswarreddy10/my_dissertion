#!/usr/bin/env python3
"""
Energy-per-MAC table: this design vs published baselines.

Project : Mixed-Precision Sparsity-Aware Systolic Array (dissertation)
Stage   : Month 4 / Week 15 - normalised pJ/MAC comparison

    pJ/MAC = power x clock_period / MACs_per_cycle
    (uW x ns x 1e-3 = pJ per cycle;  INT8 = 1 MAC/cycle, INT4x2 = 2)

Inputs  (edit these, then re-run):
    results/ours_power.csv         our measured PE power, one row per run/source
    results/published_baselines.csv  published designs; leave pj_per_mac blank to
                                   have it computed from throughput_tops/power_w/ops_per_mac,
                                   or fill pj_per_mac directly from the paper
Output  : results/pj_per_mac_table.md

To update after OpenSTA: ADD rows to ours_power.csv (same config/sparsity, source
"OpenSTA report_power total", clock_ns = the period that report used, power_uW =
total power). Keep the load-cap rows; the table shows every source side by side.

    python3 golden/pj_per_mac.py
"""
import csv
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "results")


def read(name):
    with open(os.path.join(ROOT, name), newline="") as f:
        return list(csv.DictReader(f))


def fnum(s):
    s = (s or "").strip()
    return float(s) if s else None


def main():
    lines = ["# pJ/MAC comparison", "",
             "Generated by golden/pj_per_mac.py - do not edit by hand (edit the CSVs).", "",
             "## This design (PE level, FreePDK45)", "",
             "| config | zero-operand % | mode | power (uW) | clock (ns) | pJ/MAC (nominal) | source |",
             "|---|---|---|---|---|---|---|"]
    for r in read("ours_power.csv"):
        macs = 2.0 if r["mode"].strip().lower() == "int4x2" else 1.0
        p, t = fnum(r["power_uW"]), fnum(r["clock_ns"])
        pj = "%.3f" % (p * t * 1e-3 / macs) if p is not None and t else "TBD"
        lines.append("| %s | %s | %s | %s | %s | %s | %s |" % (
            r["config"], r["sparsity_pct"], r["mode"], r["power_uW"] or "TBD", r["clock_ns"], pj, r["source"]))

    lines += ["", "## Published baselines", "",
              "| design | node | precision | pJ/MAC | basis | source | status |",
              "|---|---|---|---|---|---|---|"]
    for r in read("published_baselines.csv"):
        pj = fnum(r["pj_per_mac"])
        if pj is None and fnum(r["throughput_tops"]) and fnum(r["power_w"]) and fnum(r["ops_per_mac"]):
            macs_per_s = fnum(r["throughput_tops"]) * 1e12 / fnum(r["ops_per_mac"])
            pj = fnum(r["power_w"]) / macs_per_s * 1e12
        lines.append("| %s | %s | %s | %s | %s | %s | %s |" % (
            r["design"], r["node"], r["precision"], "%.3f" % pj if pj is not None else "TBD",
            r["basis"], r["source"], r["status"]))

    lines += ["", "## Read before quoting", "",
              "- Our power is a LOWER BOUND until OpenSTA report_power rows are added: load-capacitance switching only,",
              "  no cell-internal power, leakage, wire capacitance or clock tree; the 3 ICG latches are not cells.",
              "- Ours is a single PE (compute only); published figures are usually accelerator/system level",
              "  (SRAM/DRAM/control included). Say so next to the table - it is not a like-for-like comparison.",
              "- Process nodes differ (45 nm here). Show the node column; do not claim equivalence.",
              "- 'Nominal' counts every cycle's MAC, zero-operand ones included. State this choice in the text.",
              "- Count 1 MAC = 2 ops when converting TOPS (done in the A100 row via ops_per_mac).",
              "- INT4x2 rows are missing: run the power stimulus with TB_POWER_MODE=int4x2 (2 MACs/cycle) first."]
    out = os.path.join(ROOT, "pj_per_mac_table.md")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))
    print("\nWrote", out)


if __name__ == "__main__":
    main()
